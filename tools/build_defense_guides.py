class Guide:
    def __init__(self, number):
        self.number = number
        self.story = []
        self.titles = []

    def page(self, title):
        if self.story:
            self.story.append(PageBreak())
        self.titles.append(title)
        self.p(title, 'h1')

    def p(self, text, style='body'):
        self.story.append(Paragraph(text, STYLES[style]))

    def h(self, text):
        self.p(text, 'h2')

    def code(self, text):
        self.story.append(Preformatted(text.strip('\n'), STYLES['code']))

    def table(self, rows, widths):
        cells = [[Paragraph(str(c), STYLES['cell']) for c in row] for row in rows]
        table = Table(cells, colWidths=widths, repeatRows=1, hAlign='LEFT')
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#DFEAF0')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F1F5F8')]),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('LEFTPADDING', (0, 0), (-1, -1), 8), ('RIGHTPADDING', (0, 0), (-1, -1), 8),
            ('TOPPADDING', (0, 0), (-1, -1), 6), ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('LINEBELOW', (0, 0), (-1, 0), 0.7, colors.HexColor('#B6CAD6')),
        ]))
        self.story.extend([table, Spacer(1, 9)])

    def save(self):
        target = OUTPUT / f'lab{self.number}_defense_guide.pdf'

        def decorate(canvas, doc):
            width, height = A4
            canvas.saveState()
            canvas.setFont('Arial', 8)
            canvas.setFillColor(colors.HexColor('#52606D'))
            canvas.drawString(48, height - 28, 'OpenMP | Подготовка к сдаче')
            canvas.drawRightString(width - 48, height - 28, f'Лабораторная работа №{self.number}')
            canvas.setStrokeColor(colors.HexColor('#CCD8E1'))
            canvas.line(48, height - 37, width - 48, height - 37)
            canvas.line(48, 34, width - 48, 34)
            canvas.drawString(48, 21, 'ParallelProgramming | 29 октября 2026')
            canvas.drawRightString(width - 48, 21, str(doc.page))
            canvas.restoreState()

        doc = SimpleDocTemplate(str(target), pagesize=A4, leftMargin=48, rightMargin=48,
                                topMargin=53, bottomMargin=45,
                                title=f'Лабораторная работа №{self.number}: подготовка к сдаче',
                                author='ParallelProgramming')
        doc.build(self.story, onFirstPage=decorate, onLaterPages=decorate)
        pages = PdfReader(target).pages
        assert len(pages) == len(self.titles), (target, len(pages), len(self.titles))
        print(target.name, len(pages), 'pages')
        for i, page in enumerate(pages, 1):
            text = page.extract_text()
            assert len(text) > 500
            assert '&lt;' not in text and '&amp;' not in text and '\ufffd' not in text
            print(i, len(text), self.titles[i - 1])


